// Copies Newsroom stories from one CMS to another - typically a dev database into production -
// including the images they reference, so the Media page is not blank on the deployed site.
//
//   SOURCE_CMS_URL=http://localhost:3020 CMS_URL=https://velos2.vercel.app node scripts/copy-newsroom.mjs
//
// Why a script and not a database copy: the bodies are Lexical JSON that point at media ids, and ids
// differ between databases. Every referenced image is uploaded to the target first, then the article
// is rewritten with the new ids. Cover images and inline body images both go through that mapping.
//
// Safe to re-run: a story whose slug already exists on the target is updated in place.
//
// Serverless request bodies are capped at 4.5MB, so an image larger than MAX_UPLOAD_BYTES is resized
// with sharp before upload. The display sizes are generated by Payload anyway; this only bounds the
// original.

import 'dotenv/config'

import sharp from 'sharp'

import { api, required } from './cms-http.mjs'

const SOURCE = (process.env.SOURCE_CMS_URL || 'http://localhost:3020').replace(/\/+$/, '')
const TARGET = (process.env.CMS_URL || required('NEXT_PUBLIC_SERVER_URL')).replace(/\/+$/, '')
const EMAIL = required('SEED_ADMIN_EMAIL')
const PASSWORD = required('SEED_ADMIN_PASSWORD')
const MAX_UPLOAD_BYTES = 3.5 * 1024 * 1024
const MAX_EDGE = 2000

const loginAt = async (base) => {
  const response = await fetch(`${base}/api/users/login/`, {
    body: JSON.stringify({ email: EMAIL, password: PASSWORD }),
    headers: { 'Content-Type': 'application/json' },
    method: 'POST',
  })
  const body = await response.json()
  if (!body?.token) {
    throw new Error(`login failed at ${base} (HTTP ${response.status})`)
  }
  return body.token
}

const getJson = async (base, path, token) => {
  const response = await fetch(base + path, { headers: { Authorization: `JWT ${token}` } })
  if (!response.ok) {
    throw new Error(`GET ${base}${path} -> HTTP ${response.status}`)
  }
  return response.json()
}

/** Every media id an article points at: the cover plus any inline upload node in the body. */
const mediaIds = (doc) => {
  const ids = new Set()
  const cover = doc.coverImage
  const id = typeof cover === 'object' && cover !== null ? cover.id : cover
  if (id) {
    ids.add(String(id))
  }
  const walk = (node) => {
    if (Array.isArray(node)) {
      node.forEach(walk)
      return
    }
    if (node && typeof node === 'object') {
      if (node.type === 'upload' && node.value) {
        ids.add(String(node.value))
      }
      Object.values(node).forEach(walk)
    }
  }
  walk(doc.body)
  return [...ids]
}

const remap = (node, map) => {
  if (Array.isArray(node)) {
    return node.map((entry) => remap(entry, map))
  }
  if (node && typeof node === 'object') {
    const out = {}
    for (const [key, value] of Object.entries(node)) {
      out[key] = key === 'value' && node.type === 'upload' ? map[String(value)] ?? value : remap(value, map)
    }
    return out
  }
  return node
}

/** Downloads a source asset and shrinks it only when it would blow the serverless body limit. */
const prepareFile = async (media, token) => {
  const url = media.url.startsWith('http') ? media.url : SOURCE + media.url
  const response = await fetch(url, { headers: { Authorization: `JWT ${token}` } })
  if (!response.ok) {
    throw new Error(`download failed for ${media.filename} (HTTP ${response.status})`)
  }
  let bytes = Buffer.from(await response.arrayBuffer())
  let filename = media.filename
  let mimeType = media.mimeType
  if (bytes.length > MAX_UPLOAD_BYTES && mimeType.startsWith('image/')) {
    const image = sharp(bytes).rotate()
    const meta = await image.metadata()
    const resized = await image
      .resize({ width: Math.min(meta.width ?? MAX_EDGE, MAX_EDGE), withoutEnlargement: true })
      .jpeg({ quality: 84, mozjpeg: true })
      .toBuffer()
    console.log(`  > ${filename} ${(bytes.length / 1048576).toFixed(1)}MB exceeds the upload cap, sent as ${(resized.length / 1048576).toFixed(1)}MB jpeg`)
    bytes = resized
    filename = filename.replace(/\.[^.]+$/, '') + '.jpg'
    mimeType = 'image/jpeg'
  }
  return { bytes, filename, mimeType }
}

const uploadMedia = async (media, token) => {
  const { bytes, filename, mimeType } = await prepareFile(media, token)
  const form = new FormData()
  form.set('_payload', JSON.stringify({ alt: media.alt || filename, caption: media.caption ?? undefined }))
  form.set('file', new Blob([bytes], { type: mimeType }), filename)
  const response = await fetch(`${TARGET}/api/media/`, {
    body: form,
    headers: { Authorization: `JWT ${token}` },
    method: 'POST',
  })
  const body = await response.json().catch(() => null)
  if (!response.ok || !body?.doc?.id) {
    throw new Error(`upload failed for ${filename} (HTTP ${response.status}) ${JSON.stringify(body).slice(0, 300)}`)
  }
  console.log(`  uploaded ${filename} -> media ${body.doc.id}`)
  return body.doc
}

const main = async () => {
  console.log(`source ${SOURCE}\ntarget ${TARGET}\n`)
  const sourceToken = await loginAt(SOURCE)
  const targetToken = await loginAt(TARGET)

  const sourceArticles = await getJson(SOURCE, '/api/newsroom-articles/?limit=200&depth=0&draft=true', sourceToken)
  const targetArticles = await getJson(TARGET, '/api/newsroom-articles/?limit=200&depth=0&draft=true', targetToken)
  const targetBySlug = new Map((targetArticles.docs ?? []).map((doc) => [doc.slug, doc]))
  const targetMedia = await getJson(TARGET, '/api/media/?limit=200&depth=0', targetToken)
  const targetByFilename = new Map((targetMedia.docs ?? []).map((doc) => [doc.filename, doc]))

  console.log(`1. images (${sourceArticles.docs?.length ?? 0} stories on the source)`)
  const map = new Map()
  const wanted = [...new Set((sourceArticles.docs ?? []).flatMap(mediaIds))]
  for (const id of wanted) {
    const media = await getJson(SOURCE, `/api/media/${id}`, sourceToken)
    const already = targetByFilename.get(media.filename)
    if (already) {
      console.log(`  reused   ${media.filename} -> media ${already.id}`)
      map.set(String(id), already.id)
      continue
    }
    const uploaded = await uploadMedia(media, targetToken)
    targetByFilename.set(uploaded.filename, uploaded)
    map.set(String(id), uploaded.id)
  }

  console.log(`\n2. stories`)
  const results = []
  for (const doc of sourceArticles.docs ?? []) {
    const cover = doc.coverImage
    const coverId = typeof cover === 'object' && cover !== null ? cover.id : cover
    const payload = {
      _status: doc._status ?? 'published',
      authorName: doc.authorName,
      authorRole: doc.authorRole ?? undefined,
      body: remap(doc.body, map),
      category: doc.category,
      coverImage: coverId ? map.get(String(coverId)) ?? null : null,
      coverImageCaption: doc.coverImageCaption ?? undefined,
      featured: doc.featured === true,
      publishAt: doc.publishAt,
      readingTime: doc.readingTime ?? undefined,
      schedulePublication: doc.schedulePublication === true,
      seoDescription: doc.seoDescription ?? undefined,
      seoTitle: doc.seoTitle ?? undefined,
      slug: doc.slug,
      summary: doc.summary,
      tags: (doc.tags ?? []).map((entry) => ({ tag: entry.tag })),
      title: doc.title,
    }
    const existing = targetBySlug.get(doc.slug)
    const response = await api(existing ? 'PATCH' : 'POST', existing ? `/api/newsroom-articles/${existing.id}/` : '/api/newsroom-articles/', {
      body: payload,
      token: targetToken,
    })
    const ok = response.status < 400
    results.push(ok)
    console.log(`  ${ok ? (existing ? 'updated ' : 'created ') : 'FAILED  '} ${doc.slug} [${doc.category}] HTTP ${response.status}`)
    if (!ok) {
      console.log('   ', JSON.stringify(response.body).slice(0, 300))
    }
  }

  const after = await getJson(TARGET, '/api/newsroom-articles/?limit=200&depth=0', targetToken)
  console.log(`\n3. result`)
  console.log(`  published stories visible on the target: ${after.totalDocs ?? 0}`)
  console.log(`  ${results.filter(Boolean).length}/${results.length} stories copied, ${map.size} images mapped`)
  if (results.some((ok) => !ok)) {
    process.exit(1)
  }
}

main().catch((error) => {
  console.error('copy-newsroom failed:', error.message)
  process.exit(1)
})
